USE ROLE TL_ANALYST;
SELECT 'TL_ANALYST' AS ROLE_USED, COUNT(*) AS CUSTOMERS_VISIBLE, LISTAGG(DISTINCT REGION, ',') AS REGIONS,
       MAX(IFF(CUSTOMER_ID = 'CUST-0001', FULL_NAME || ' | ' || PAN_NUMBER || ' | ' || PHONE, NULL)) AS CUST_0001
FROM TRACELEDGER.CORE.CUSTOMERS;

USE ROLE TL_AUDITOR;
SELECT 'TL_AUDITOR' AS ROLE_USED, COUNT(*) AS CUSTOMERS_VISIBLE, LISTAGG(DISTINCT REGION, ',') AS REGIONS,
       MAX(IFF(CUSTOMER_ID = 'CUST-0001', FULL_NAME || ' | ' || PAN_NUMBER || ' | ' || PHONE, NULL)) AS CUST_0001
FROM TRACELEDGER.CORE.CUSTOMERS;

